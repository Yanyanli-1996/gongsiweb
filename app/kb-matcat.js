function excluded(matKind, cat){
  var list = EXCLUDE[matKind];
  if(!list) return false;
  if(list.indexOf(cat) > -1) return true;
  // 前缀匹配（「柜类」应拦住「衣柜」「餐边柜」等）
  return list.some(function(x){
    return cat.indexOf(x) === 0 || cat.indexOf(x) > -1;
  });
}

