/* 判断规则 */
function canApply(matKind, catKind){
  if(!matKind || !catKind) return false;

  // 床垫：只配床垫填充
  if(catKind === '床垫')
    return matKind === '床垫填充';

  // 软体家具：皮面 / 布料 / 软体填充 / 木质框架 / 板材
  if(catKind === '软体')
    return ['皮面','布料','软体填充','木质','板材'].indexOf(matKind) > -1;

  // 硬体家具：木质 / 板材 / 台面 / 皮面(床头软包) / 五金
  if(catKind === '硬体')
    return ['木质','板材','台面','皮面','五金件','透明件','结构件'].indexOf(matKind) > -1;

  // 功能件
  if(catKind === '功能件') return matKind === '功能件';

  return false;
}

