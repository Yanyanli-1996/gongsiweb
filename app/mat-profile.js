  /* 归一化材质名：返回标准名 */
  function normalize(material){
    var m = String(material || '').trim();
    if(!m) return '其他';
    // 完全相等
    if(PROFILES[m]) return m;
    // 别名精确匹配（长别名优先，避免「实木」吃掉「实木排骨架」）
    var aliases = [];
    Object.keys(PROFILES).forEach(function(k){
      (PROFILES[k].alias || []).forEach(function(a){ aliases.push([a, k]); });
    });
    aliases.sort(function(a, b){ return b[0].length - a[0].length; });
    for(var i = 0; i < aliases.length; i++){
      if(m === aliases[i][0]) return aliases[i][1];
    }
    // 包含匹配（长别名优先）
    for(var j = 0; j < aliases.length; j++){
      if(m.indexOf(aliases[j][0]) > -1) return aliases[j][1];
    }
    // 标准名包含
    var names = Object.keys(PROFILES).sort(function(a, b){ return b.length - a.length; });
    for(var k = 0; k < names.length; k++){
      if(names[k] !== '其他' && m.indexOf(names[k]) > -1) return names[k];
    }
    return '其他';
  }

  function get(name){
    return PROFILES[name] || PROFILES['其他'];
  }

  window.KB_MAT_PROFILE = { table: PROFILES, normalize: normalize, get: get };
